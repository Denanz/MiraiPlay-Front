// Разнообразие «на каждый вход» для подборок на главной.
//
// Сид считается один раз при первом импорте модуля, то есть живёт ровно один
// запуск приложения (или одну загрузку вкладки). Это осознанный компромисс:
// брать Math.random() прямо в компоненте нельзя — тогда лента перетасовывалась бы
// при каждом возврате на главную, а хранить сид в localStorage не нужно, потому
// что новый вход как раз и должен давать новую подборку.
export const SESSION_SEED = (Math.random() * 2 ** 32) >>> 0

/** Маленький детерминированный ГПСЧ: одинаковый сид → одинаковая последовательность. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Тасовка Фишера—Йетса на переданном ГПСЧ. Исходный массив не меняется. */
export function shuffled<T>(list: T[], rnd: () => number): T[] {
  const a = [...list]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}
